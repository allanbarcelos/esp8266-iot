"""Generates HtmlPairs.h: the byte pairs that pack the panel's fixed HTML.

The page text written with H("...") or HTML_TEXT(name, "...")
(WebService.h) is ASCII. The compiler packs it (HtmlPack.h, constexpr):
each pair of this table, in order, turns every occurrence of its two bytes
into one byte, 0x80 + its index; a half of a pair can be an earlier pair.
The device expands it as the page goes out. This tool only picks the pairs
(the most frequent first, over the distinct texts, since the linker merges
equal strings): a stale table still packs and expands correctly, only less.
It also refuses a non-ASCII literal in the panel's sources: any PGM_P can
reach the page, and a byte from 0x80 up would go out as a pair.

Usage:
    python tools/html_pairs.py           writes HtmlPairs.h
    python tools/html_pairs.py --check   only checks (CI uses it); exits with
                                         an error if HtmlPairs.h is stale
The generated HtmlPairs.h goes into the repository: the build does not need this tool.
"""
import collections
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SOURCES = ["WebService.h"]
PANEL = ["WebService.h", "IoTCatalog.h", "I18n.h"]
CODE = 0x80
MAX_PAIRS = 128
LIT = r'"(?:[^"\\]|\\.)*"'
TOKENS = r"(?:\s*(?:" + LIT + r"|[A-Z_][A-Z0-9_]*))+"


def read(name):
    with open(os.path.join(ROOT, name), encoding="utf-8") as f:
        return f.read()


def macros():
    defs = {}
    for name in sorted(f for f in os.listdir(ROOT) if f.endswith(".h")):
        for m in re.finditer(r"#define\s+(\w+)\s+((?:" + LIT + r"\s*)+)", read(name)):
            defs[m.group(1)] = m.group(2)
    return defs


def value(tokens, defs):
    out = b""
    for lit, ident in re.findall("(" + LIT + r")|(\w+)", tokens):
        if lit:
            out += lit[1:-1].encode("ascii").decode("unicode_escape").encode("latin-1")
        else:
            out += value(defs[ident], defs)
    return out


def texts():
    """The distinct H() texts, as the compiler sees them."""
    defs = macros()
    found = set()
    for name in SOURCES:
        for m in re.finditer(r"\b(?:H\(|HTML_TEXT\(\s*\w+\s*,)(" + TOKENS + r")\s*\)", read(name)):
            found.add(value(m.group(1), defs))
    return sorted(found)


def not_ascii():
    """String literals with a byte from 0x80 up in the panel's sources (the
    page, the IoT names it writes): a PGM_P turns into an Html, so such a
    byte would go out as a pair."""
    token = re.compile(r"//[^\n]*|/\*.*?\*/|" + LIT + r"|'(?:[^'\\]|\\.)*'", re.S)
    high = re.compile(r"[^\x00-\x7f]|\\x[89a-fA-F][0-9a-fA-F]|\\[23][0-7][0-7]")
    bad = []
    for name in PANEL:
        for m in token.finditer(read(name)):
            s = m.group(0)
            if s[0] in "\"'" and high.search(s):
                bad.append(f"{name}: {s[:60]}")
    return bad


def pack(seq, a, b, code):
    """The same pass as html::encode: left to right, no overlap."""
    out = []
    i = 0
    while i < len(seq):
        if i + 1 < len(seq) and seq[i] == a and seq[i + 1] == b:
            out.append(code)
            i += 2
        else:
            out.append(seq[i])
            i += 1
    return out


def pairs(found):
    """A pair is worth its two table bytes when it occurs three times or more."""
    seqs = [list(t) for t in found]
    chosen = []
    while len(chosen) < MAX_PAIRS:
        count = collections.Counter()
        for s in seqs:
            count.update(zip(s, s[1:]))
        if not count:
            break
        (a, b), n = max(count.items(), key=lambda kv: (kv[1], -kv[0][0], -kv[0][1]))
        if n < 3:
            break
        code = CODE + len(chosen)
        chosen.append((a, b))
        seqs = [pack(s, a, b, code) for s in seqs]
    return chosen, sum(len(s) + 1 for s in seqs)


def show(byte, table):
    """What a table byte stands for, for the comment."""
    if byte < CODE:
        return chr(byte)
    a, b = table[byte - CODE]
    return show(a, table) + show(b, table)


def header(table, raw, packed):
    rows = []
    for a, b in table:
        text = show(a, table) + show(b, table)
        rows.append(f"    {{0x{a:02x}, 0x{b:02x}}},  // {text!r}")
    body = "\n".join(rows)
    return (
        "// SPDX-License-Identifier: MIT\n"
        "// Copyright (c) 2026 Allan Barcelos. ESP8266 IoT: "
        "https://github.com/allanbarcelos/esp8266-iot\n\n"
        "#pragma once\n"
        "// Generated by tools/html_pairs.py from the H() texts. Do not edit.\n"
        "#include <Arduino.h>\n\n"
        f"// Byte 0x80 + i of a packed text stands for pair i ({raw} bytes of\n"
        f"// distinct texts become {packed} plus this table)\n"
        f"static constexpr uint8_t HTML_PAIR_COUNT = {len(table)};\n"
        "static constexpr uint8_t HTML_PAIRS[][2] PROGMEM = {\n"
        f"{body}\n"
        "};\n"
    )


def main():
    bad = not_ascii()
    if bad:
        sys.exit("Not ASCII (write an HTML entity, such as &ccedil;):\n  " + "\n  ".join(bad))
    found = texts()
    table, packed = pairs(found)
    raw = sum(len(t) + 1 for t in found)
    text = header(table, raw, packed)
    path = os.path.join(ROOT, "HtmlPairs.h")
    if "--check" in sys.argv[1:]:
        with open(path, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit("HtmlPairs.h is stale: run python tools/html_pairs.py")
        print("HtmlPairs.h matches")
        return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"HtmlPairs.h: {len(found)} texts, {raw} -> {packed} bytes, "
          f"{len(table)} pairs ({2 * len(table)} bytes)")


if __name__ == "__main__":
    main()
